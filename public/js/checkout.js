function renderCarrinho(){const el=document.querySelector('#carrinho');
const total=document.querySelector('#total');
const c=lerCarrinho();
if(!el||!total)return;
if(c.length===0){el.innerHTML='<div class="alert alert-info">Seu carrinho está vazio. <a href="produtos.php">Ver produtos</a></div>';
total.textContent=moeda(0);
return;
}let soma=0;
const rows=c.map((i,index)=>{soma+=i.preco*i.quantidade;
return `<tr><td>${i.nome}</td><td>${moeda(i.preco)}</td><td><input class="form-control qtd" data-index="${index}" type="number" min="1" value="${i.quantidade}"></td><td>${moeda(i.preco*i.quantidade)}</td><td><button class="btn btn-sm btn-danger remover" data-index="${index}">Excluir</button></td></tr>`}).join('');
el.innerHTML=`<div class="table-responsive"><table class="table bg-white"><thead><tr><th>Produto</th><th>Preço</th><th>Qtd.</th><th>Subtotal</th><th></th></tr></thead><tbody>${rows}</tbody></table></div>`;
total.textContent=moeda(soma);
el.querySelectorAll('.qtd').forEach(x=>x.addEventListener('change',e=>{const i=Number(e.target.dataset.index);
const v=Math.max(1,Number(e.target.value));
c[i].quantidade=v;
salvarCarrinho(c);
renderCarrinho();
}));
el.querySelectorAll('.remover').forEach(x=>x.addEventListener('click',e=>{c.splice(Number(e.target.dataset.index),1);
salvarCarrinho(c);
renderCarrinho();
}));
}
document.querySelector('#checkoutForm')?.addEventListener('submit',async e=>{e.preventDefault();
const resultado=document.querySelector('#resultado');
const c=lerCarrinho();
if(c.length===0){resultado.innerHTML='<div class="alert alert-warning">Adicione produtos antes de finalizar.</div>';
return;
}const form=new FormData(e.target);
const cliente=Object.fromEntries(form.entries());
try{const r=await fetch('../api/checkout.php',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({cliente,itens:c})});
const data=await r.json();
if(!r.ok||!data.ok)throw new Error(data.mensagem||'Erro ao finalizar.');
resultado.innerHTML=`<div class="alert alert-success">${data.mensagem} Número do pedido: <strong>${data.venda_id}</strong></div>`;
salvarCarrinho([]);
renderCarrinho();
e.target.reset();
}catch(err){resultado.innerHTML=`<div class="alert alert-danger">${err instanceof Error?err.message:'Erro inesperado.'}</div>`;
}});
renderCarrinho();
