const api={produtos:'../api/produtos.php',categorias:'../api/categorias.php',clientes:'../api/clientes.php'};
async function getJson(url){const r=await fetch(url);
if(!r.ok)throw new Error('Erro na API');
return r.json();
}
function formDataObj(form){return Object.fromEntries(new FormData(form).entries());
}
async function enviar(url,method,data){const r=await fetch(url,{method,headers:{'Content-Type':'application/json'},body:JSON.stringify(data)});
const d=await r.json();
if(!r.ok||!d.ok)throw new Error(d.mensagem||'Operação não realizada');
return d;
}
let categorias=[];
async function carregar(){categorias=await getJson(api.categorias);
document.querySelector('#categoriaSelect').innerHTML=categorias.map(c=>`<option value="${c.id}">${c.nome}</option>`).join('');
const ps=await getJson(api.produtos);
document.querySelector('#prodTabela').innerHTML=`<table class="table"><tr><th>Nome</th><th>Preço</th><th>Estoque</th><th>Ações</th></tr>${ps.map(p=>`<tr><td>${p.nome}</td><td>${moeda(p.preco)}</td><td>${p.estoque}</td><td><button class="btn btn-sm btn-outline-dark editarP" data-id="${p.id}">Editar</button> <button class="btn btn-sm btn-danger excluirP" data-id="${p.id}">Excluir</button></td></tr>`).join('')}</table>`;
const cs=await getJson(api.categorias);
document.querySelector('#catTabela').innerHTML=`<table class="table"><tr><th>Nome</th><th>Ações</th></tr>${cs.map(c=>`<tr><td>${c.nome}</td><td><button class="btn btn-sm btn-outline-dark editarC" data-id="${c.id}">Editar</button> <button class="btn btn-sm btn-danger excluirC" data-id="${c.id}">Excluir</button></td></tr>`).join('')}</table>`;
const cl=await getJson(api.clientes);
document.querySelector('#cliTabela').innerHTML=`<table class="table"><tr><th>Nome</th><th>E-mail</th><th>Ações</th></tr>${cl.map(c=>`<tr><td>${c.nome}</td><td>${c.email}</td><td><button class="btn btn-sm btn-outline-dark editarL" data-id="${c.id}">Editar</button> <button class="btn btn-sm btn-danger excluirL" data-id="${c.id}">Excluir</button></td></tr>`).join('')}</table>`;
}
function limpar(id){document.querySelector(id).reset();
document.querySelector(`${id} [name=id]`).value='';
}
document.querySelector('#produtoForm').addEventListener('submit',async e=>{e.preventDefault();
try{const d=formDataObj(e.target);
d.categoria_id=Number(d.categoria_id);
d.preco=Number(d.preco);
d.estoque=Number(d.estoque);
const method=d.id?'PUT':'POST';
await enviar(api.produtos,method,d);
alert('Produto salvo com sucesso!');
limpar('#produtoForm');
carregar();
}catch(x){alert(x.message);
}});
document.querySelector('#categoriaForm').addEventListener('submit',async e=>{e.preventDefault();
try{const d=formDataObj(e.target);
await enviar(api.categorias,d.id?'PUT':'POST',d);
alert('Categoria salva!');
limpar('#categoriaForm');
carregar();
}catch(x){alert(x.message);
}});
document.querySelector('#clienteForm').addEventListener('submit',async e=>{e.preventDefault();
try{const d=formDataObj(e.target);
await enviar(api.clientes,d.id?'PUT':'POST',d);
alert('Cliente salvo!');
limpar('#clienteForm');
carregar();
}catch(x){alert(x.message);
}});
document.querySelector('#cancelarProduto').addEventListener('click',()=>limpar('#produtoForm'));
document.addEventListener('click',async e=>{const b=e.target.closest('button');
if(!b)return;
const id=Number(b.dataset.id);
try{if(b.classList.contains('excluirP')){if(!confirm('Tem certeza que deseja excluir este produto?'))return;
await enviar(api.produtos,'DELETE',{id});
alert('Produto excluído.');
carregar();
}else if(b.classList.contains('excluirC')){if(!confirm('Excluir categoria? Só será possível se ela não possuir produtos.'))return;
await enviar(api.categorias,'DELETE',{id});
alert('Categoria excluída.');
carregar();
}else if(b.classList.contains('excluirL')){if(!confirm('Excluir cliente?'))return;
await enviar(api.clientes,'DELETE',{id});
alert('Cliente excluído.');
carregar();
}else if(b.classList.contains('editarP')){const p=(await getJson(api.produtos)).find(x=>x.id===id);
for(const [k,v] of Object.entries(p)){const el=document.querySelector(`#produtoForm [name="${k}"]`);
if(el)el.value=v;
} }else if(b.classList.contains('editarC')){const c=categorias.find(x=>x.id===id);
for(const [k,v] of Object.entries(c)){const el=document.querySelector(`#categoriaForm [name="${k}"]`);
if(el)el.value=v;
}}else if(b.classList.contains('editarL')){const cs=await getJson(api.clientes);
const c=cs.find(x=>x.id===id);
for(const [k,v] of Object.entries(c)){const el=document.querySelector(`#clienteForm [name="${k}"]`);
if(el)el.value=v;
}}}catch(x){alert(x.message);
}});
carregar().catch(e=>alert(e.message));
